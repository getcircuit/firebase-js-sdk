#!/usr/bin/env bash
# Builds a Yarn patch for the published @firebase/firestore package from this branch.
#
# Usage: spoke-patch/build-patch.sh <base-tag> <output.patch> [existing.patch ...]
#   base-tag        the upstream release tag this branch is based on, eg. firebase@12.15.0
#   output.patch    where to write the patch
#   existing.patch  patches the consumer already applies to this package version. A patch
#                   this script generated is replaced as a whole. Any other patch must
#                   already be part of this branch: the script stops unless every one of
#                   its changes is present in the new build, so moving to the generated
#                   patch never drops a change.
#
# Requires `yarn` (install) and the builds of Firestore's dependencies, from the repository root:
#   yarn && yarn --cwd packages/firestore build:deps
#
# Steps:
# 0. Stops unless test/unit/core/upstream_view.ts is the View of the base tag, so the
#    comparison tests ran against the release the patch applies to.
# 1. Downloads the published package for the version in packages/firestore/package.json.
# 2. Builds the base tag and stops unless every main bundle and type rollup is
#    byte-identical to the published one, so the patch only ever changes what this
#    branch changes.
# 3. Builds this branch with the base build's terser name cache. Without it, every new
#    private property shifts the mangled names of the ones after it (`this.R` becomes
#    `this.I`), and each minified bundle changes on thousands of lines instead of hundreds.
# 4. Maps the new chunk file names back to the published ones, diffs each changed file
#    and writes the patch: a banner saying where it came from, patch-header.txt, then
#    the diff.
set -euo pipefail

BASE=${1:?base tag, eg. firebase@12.15.0}
OUT=$(cd "$(dirname "${2:?output patch path}")" && pwd)/$(basename "$2")
shift 2
EXISTING=()
for patch in "$@"; do EXISTING+=("$(cd "$(dirname "$patch")" && pwd)/$(basename "$patch")"); done

ROOT=$(git rev-parse --show-toplevel)
HERE=$ROOT/spoke-patch
PKG=$ROOT/packages/firestore
VERSION=$(node -p "require('$PKG/package.json').version")
COMMIT=$(git -C "$ROOT" rev-parse HEAD)
BRANCH=$(git -C "$ROOT" rev-parse --abbrev-ref HEAD)
BANNER_MARK='# GENERATED by spoke-patch/build-patch.sh'
WORK=$(mktemp -d)
trap 'git -C "$ROOT" worktree remove --force "$WORK/base" >/dev/null 2>&1 || true; rm -rf "$WORK"' EXIT

if [ -n "$(git -C "$ROOT" status --porcelain -- packages/firestore common/api-review spoke-patch)" ]; then
  echo "packages/firestore, common/api-review or spoke-patch has uncommitted changes; commit them first" >&2
  exit 1
fi
if [ -z "$(git -C "$ROOT" branch -r --contains "$COMMIT")" ]; then
  echo "warning: $COMMIT is on no remote branch yet; push it before shipping this patch" >&2
fi
"$HERE/upstream-view.sh" "$BASE" --check

echo "Downloading @firebase/firestore@$VERSION"
(cd "$WORK" && npm pack "@firebase/firestore@$VERSION" --silent >/dev/null && mkdir npm && tar -xzf ./*.tgz -C npm)
PUBLISHED=$WORK/npm/package/dist

echo "Preparing a checkout of $BASE"
git -C "$ROOT" worktree add --detach "$WORK/base" "$BASE" >/dev/null 2>&1
# The base build needs this branch's rollup.shared.js, which loads and saves the name cache.
# With NC_IN and NC_OUT unset it builds exactly what upstream's does.
git -C "$WORK/base" checkout "$COMMIT" -- packages/firestore/rollup.shared.js
ln -s "$ROOT/node_modules" "$WORK/base/node_modules"
[ -d "$PKG/node_modules" ] && ln -s "$PKG/node_modules" "$WORK/base/packages/firestore/node_modules"
for dist in "$ROOT"/packages/*/dist; do
  name=$(basename "$(dirname "$dist")")
  [ "$name" = firestore ] || ln -sfn "$dist" "$WORK/base/packages/$name/dist"
done

# The bundle build reads the public declarations of a previous build to decide which names
# it may mangle: the packages/firestore/dist/ entries of externs.json. Seed them from the
# published package, which comes from the same source, so both builds mangle alike.
SEEDS=$(node -e '
  const { externs } = require(process.argv[1]);
  const prefix = "packages/firestore/dist/";
  for (const e of externs) if (e.startsWith(prefix)) console.log(e.slice(prefix.length));
' "$PKG/externs.json")
seed() {
  rm -rf "$1/dist"
  for f in $SEEDS; do
    mkdir -p "$(dirname "$1/dist/$f")"
    cp "$PUBLISHED/$f" "$1/dist/$f"
  done
}

# Bundles, then type rollups, the way the release build makes them. tsc and rollup exit
# non-zero on errors outside what the patch uses (auth's gapi types, the global.d.ts
# bundle); compare-build.mjs then checks every file the patch covers.
build() {
  local dir=$1 label=$2
  (cd "$dir" && npx rollup -c rollup.config.js > "$WORK/$label-bundles.log" 2>&1) || true
  (cd "$dir" && npx tsc --emitDeclarationOnly --declaration -p tsconfig.json > "$WORK/$label-tsc.log" 2>&1) || true
  for script in api-report:main api-report:pipelines api-report:lite api-report:lite:pipelines; do
    (cd "$dir" && npm run --silent "$script" >> "$WORK/$label-types.log" 2>&1) || {
      echo "$script failed for $label; see below" >&2; tail -20 "$WORK/$label-types.log" >&2; exit 1
    }
  done
}

echo "Building $BASE"
seed "$WORK/base/packages/firestore"
NC_OUT=$WORK/name-cache.json build "$WORK/base/packages/firestore" base
node "$HERE/compare-build.mjs" "$PUBLISHED" "$WORK/base/packages/firestore/dist" --expect-identical

echo "Building $BRANCH ($(git -C "$ROOT" rev-parse --short HEAD))"
seed "$PKG"
NC_IN=$WORK/name-cache.json build "$PKG" patched
# The api-report scripts also rewrite the tracked API reports.
git -C "$ROOT" checkout -- common/api-review
node "$HERE/compare-build.mjs" "$PUBLISHED" "$PKG/dist" --write "$WORK/normalized"

# The published package with the new build's files on top, to check existing patches against.
cp -R "$WORK/npm/package" "$WORK/patched-package"
cp -R "$WORK/normalized/." "$WORK/patched-package/dist/"
for patch in ${EXISTING[@]+"${EXISTING[@]}"}; do
  if grep -q "^$BANNER_MARK" "$patch"; then
    echo "Replacing $(basename "$patch"), an earlier generated patch"
  elif (cd "$WORK/patched-package" && git apply --reverse --check "$patch" 2>/dev/null); then
    echo "Replacing $(basename "$patch"): the new build already contains all of its changes"
  else
    echo "$(basename "$patch") has changes the new build does not contain. Move them into" >&2
    echo "this branch first (one commit each), then build again." >&2
    exit 1
  fi
done

echo "Writing $OUT"
{
  cat <<BANNER
$BANNER_MARK. Do not edit it by hand.
#
# Source:  github.com/getcircuit/firebase-js-sdk, branch $BRANCH, commit $COMMIT
# Base:    $BASE. Its build matched the published @firebase/firestore@$VERSION byte for
#          byte, so the diff below holds only the changes on $BRANCH.
# Rebuild: spoke-patch/build-patch.sh $BASE <output.patch> [existing.patch ...]
#          (spoke-patch/README.md has the full steps, including upgrades)
#
BANNER
  sed -e "s/{{FIRESTORE_VERSION}}/$VERSION/g" -e "s/{{FIREBASE_VERSION}}/${BASE#firebase@}/g" \
    "$HERE/patch-header.txt"
  (cd "$WORK/normalized" && find . -type f | sed 's#^\./##' | sort) | while read -r f; do
    # git diff --no-index exits 1 when the files differ.
    (cd "$WORK" && git diff --no-index --src-prefix=a/ --dst-prefix=b/ "npm/package/dist/$f" "normalized/$f" || true) |
      sed -e "s#a/npm/package/dist/$f#a/dist/$f#g" -e "s#b/normalized/$f#b/dist/$f#g"
  done
} > "$OUT"
grep '^diff --git' "$OUT" | sed 's#^diff --git a/#  #; s# b/.*##'
